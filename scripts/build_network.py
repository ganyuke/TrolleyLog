#!/usr/bin/env python3
"""Regenerates NetworkData.kt (stations and track shapes) and TravelTimeData.kt
(scheduled ride times) from the MTS GTFS feed.

Usage:
    curl -LO https://www.sdmts.com/google_transit_files/google_transit.zip
    python3 scripts/build_network.py google_transit.zip

For each Trolley line the trip pattern with the most stops is taken as the
line. Platforms are folded into their parent station, and track shapes are
thinned with Douglas-Peucker so the file stays small.

Ride times are kept per line as the seconds between neighbouring stations in
each direction, the median over every trip in the feed. The time between
trains is kept for each of those stretches too, as the median weekday daytime
gap, because part of a line can run more often than the rest of it.
"""
import csv
import io
import math
import statistics
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

# route_id -> (line id, display name, colour). Colours are the MTS line colours,
# nudged so they stay readable on both light and dark backgrounds.
LINES = {
    "510": ("blue", "Blue Line", 0xFF2F6FED),
    "520": ("orange", "Orange Line", 0xFFF07A1A),
    "530": ("green", "Green Line", 0xFF1E9E4A),
    "535": ("copper", "Copper Line", 0xFFB87333),
}
# The Bayside platforms at 12th & Imperial are listed as their own station.
MERGE = {"imtS": "12tS"}
SIMPLIFY_METRES = 12.0
DATA = Path(__file__).resolve().parent.parent / "app/src/main/java/org/nextcolor/trolleylog/data"
OUT = DATA / "NetworkData.kt"
TIMES_OUT = DATA / "TravelTimeData.kt"
# Hours of the day used to measure how often a line runs.
DAYTIME = range(6, 19)


def read(zf, name):
    return csv.DictReader(io.TextIOWrapper(zf.open(name), encoding="utf-8-sig"))


def metres(a, b):
    k = math.cos(math.radians(32.75))
    return math.hypot((a[0] - b[0]) * 111_320, (a[1] - b[1]) * 111_320 * k)


def seg_dist(p, a, b):
    k = math.cos(math.radians(32.75))
    px, py = p[1] * k, p[0]
    ax, ay = a[1] * k, a[0]
    bx, by = b[1] * k, b[0]
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return metres(p, a)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy) * 111_320


def simplify(points, tol):
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        worst, at = 0.0, None
        for n in range(i + 1, j):
            d = seg_dist(points[n], points[i], points[j])
            if d > worst:
                worst, at = d, n
        if at is not None and worst > tol:
            keep[at] = True
            stack += [(i, at), (at, j)]
    return [p for p, k in zip(points, keep) if k]


def seconds(clock):
    h, m, s = map(int, clock.split(":"))
    return h * 3600 + m * 60 + s


def clean_name(name):
    name = name.replace(" Station", "").replace(" Bayside", "").strip()
    return name.replace("32nd/Commercial", "32nd & Commercial")


def main():
    zf = zipfile.ZipFile(sys.argv[1])
    stops = {s["stop_id"]: s for s in read(zf, "stops.txt")}
    trips = {t["trip_id"]: t for t in read(zf, "trips.txt") if t["route_id"] in LINES}
    seqs = defaultdict(list)
    clocks = defaultdict(list)
    for r in read(zf, "stop_times.txt"):
        if r["trip_id"] in trips:
            seqs[r["trip_id"]].append((int(r["stop_sequence"]), r["stop_id"]))
            clocks[r["trip_id"]].append((int(r["stop_sequence"]), r["stop_id"], seconds(r["departure_time"])))

    patterns = defaultdict(Counter)
    for tid, t in trips.items():
        if t["direction_id"] == "0":
            patterns[t["route_id"]][(t["shape_id"], tuple(s for _, s in sorted(seqs[tid])))] += 1
    chosen = {}
    for rid, counter in patterns.items():
        chosen[rid] = max(counter, key=lambda k: (len(k[1]), counter[k]))

    shapes = defaultdict(list)
    wanted = {shape for shape, _ in chosen.values()}
    for r in read(zf, "shapes.txt"):
        if r["shape_id"] in wanted:
            shapes[r["shape_id"]].append(
                (int(r["shape_pt_sequence"]), float(r["shape_pt_lat"]), float(r["shape_pt_lon"]))
            )

    stations = {}
    lines = []
    for rid, (lid, lname, colour) in LINES.items():
        shape_id, stop_ids = chosen[rid]
        ids = []
        for sid in stop_ids:
            parent = stops[sid]["parent_station"] or sid
            parent = MERGE.get(parent, parent)
            p = stops[parent]
            stations.setdefault(parent, (clean_name(p["stop_name"]), float(p["stop_lat"]), float(p["stop_lon"])))
            ids.append(parent)
        pts = [(la, lo) for _, la, lo in sorted(shapes[shape_id])]
        pts = simplify(pts, SIMPLIFY_METRES)
        lines.append((lid, lname, colour, ids, pts))

    feed = next(read(zf, "feed_info.txt"))
    out = [
        "// Generated by scripts/build_network.py from the MTS GTFS feed",
        f"// ({feed['feed_version']}). Do not edit by hand.",
        "package org.nextcolor.trolleylog.data",
        "",
        "internal val NETWORK_STATIONS: List<Station> = listOf(",
    ]
    for sid, (name, lat, lon) in stations.items():
        out.append(f'    Station("{sid}", "{name}", {lat:.6f}, {lon:.6f}),')
    out += [")", "", "internal val NETWORK_LINES: List<Line> = listOf("]
    for lid, lname, colour, ids, pts in lines:
        out.append("    Line(")
        out.append(f'        "{lid}", "{lname}", 0x{colour:08X},')
        out.append("        listOf(" + ", ".join(f'"{i}"' for i in ids) + "),")
        out.append("        floatArrayOf(")
        flat = [f"{la:.5f}f, {lo:.5f}f" for la, lo in pts]
        for i in range(0, len(flat), 4):
            out.append("            " + ", ".join(flat[i:i + 4]) + ",")
        out.append("        ),")
        out.append("    ),")
    out.append(")")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(stations)} stations, " + ", ".join(f"{l[1]} {len(l[4])} points" for l in lines))

    def station(sid):
        parent = stops[sid]["parent_station"] or sid
        return MERGE.get(parent, parent)

    weekdays = {c["service_id"] for c in read(zf, "calendar.txt") if c["wednesday"] == "1"}
    hops = defaultdict(lambda: defaultdict(list))
    leaving = defaultdict(lambda: defaultdict(list))
    for tid, t in trips.items():
        calls = [(station(sid), at) for _, sid, at in sorted(clocks[tid])]
        for (a, left), (b, arrived) in zip(calls, calls[1:]):
            if a != b:
                hops[t["route_id"]][a, b].append(arrived - left)
                if t["service_id"] in weekdays and left // 3600 in DAYTIME:
                    leaving[t["route_id"]][a, b].append(left)

    out = [
        "// Generated by scripts/build_network.py from the MTS GTFS feed",
        f"// ({feed['feed_version']}). Do not edit by hand.",
        "package org.nextcolor.trolleylog.data",
        "",
        "internal val TRAVEL_TIMES: List<LineTimes> = listOf(",
    ]
    summary = []
    for rid, (lid, lname, _) in LINES.items():
        ids = next(l[3] for l in lines if l[0] == lid)
        pairs = list(zip(ids, ids[1:]))

        def hop(a, b):
            # A stretch only ever timetabled one way takes as long the other way.
            times = hops[rid].get((a, b)) or hops[rid][b, a]
            return round(statistics.median(times))

        def every(a, b):
            # The middle half of the gaps, so 7 and 8 minute gaps in turn come out
            # as 7.5 and the odd long gap does not count.
            times = sorted(leaving[rid][a, b])
            gaps = sorted(y - x for x, y in zip(times, times[1:]))
            return round(statistics.mean(gaps[len(gaps) // 4:-(len(gaps) // 4)]))

        outbound = [hop(a, b) for a, b in pairs]
        inbound = [hop(b, a) for a, b in pairs]
        outbound_every = [every(a, b) for a, b in pairs]
        inbound_every = [every(b, a) for a, b in pairs]
        out.append("    LineTimes(")
        out.append(f'        "{lid}",')
        for name, values in [
            ("outbound", outbound), ("inbound", inbound),
            ("outboundEvery", outbound_every), ("inboundEvery", inbound_every),
        ]:
            out.append(f"        {name} = intArrayOf(" + ", ".join(map(str, values)) + "),")
        out.append("    ),")
        gaps = sorted({round(s / 60, 1) for s in outbound_every})
        summary.append(f"{lname} {round(sum(outbound) / 60)} min end to end, every " + " or ".join(f"{g:g}" for g in gaps) + " min")
    out.append(")")
    TIMES_OUT.write_text("\n".join(out) + "\n")
    print(", ".join(summary))


if __name__ == "__main__":
    main()
