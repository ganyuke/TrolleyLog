#!/usr/bin/env python3
"""Regenerates NetworkData.kt (stations and track shapes) from the MTS GTFS feed.

Usage:
    curl -LO https://www.sdmts.com/google_transit_files/google_transit.zip
    python3 scripts/build_network.py google_transit.zip

For each Trolley line the trip pattern with the most stops is taken as the
line. Platforms are folded into their parent station, and track shapes are
thinned with Douglas-Peucker so the file stays small.
"""
import csv
import io
import math
import sys
import zipfile
from collections import Counter, defaultdict
from pathlib import Path

# route_id -> (line id, display name, colour). Colours are the MTS line colours,
# nudged so they stay readable on both light and dark backgrounds.
LINES = {
    "510": ("blue", "Blue Line", 0xFF2F6FED),
    "520": ("orange", "Orange Line", 0xFFF07A1A),
    "530": ("green", "Green Line", 0xFF1E9E4A),
    "535": ("copper", "Copper Line", 0xFFB87333),
}
# The Bayside platforms at 12th & Imperial are listed as their own station.
MERGE = {"imtS": "12tS"}
SIMPLIFY_METRES = 12.0
OUT = Path(__file__).resolve().parent.parent / "app/src/main/java/org/nextcolor/trolleylog/data/NetworkData.kt"


def read(zf, name):
    return csv.DictReader(io.TextIOWrapper(zf.open(name), encoding="utf-8-sig"))


def metres(a, b):
    k = math.cos(math.radians(32.75))
    return math.hypot((a[0] - b[0]) * 111_320, (a[1] - b[1]) * 111_320 * k)


def seg_dist(p, a, b):
    k = math.cos(math.radians(32.75))
    px, py = p[1] * k, p[0]
    ax, ay = a[1] * k, a[0]
    bx, by = b[1] * k, b[0]
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return metres(p, a)
    t = max(0.0, min(1.0, ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - ax - t * dx, py - ay - t * dy) * 111_320


def simplify(points, tol):
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        i, j = stack.pop()
        worst, at = 0.0, None
        for n in range(i + 1, j):
            d = seg_dist(points[n], points[i], points[j])
            if d > worst:
                worst, at = d, n
        if at is not None and worst > tol:
            keep[at] = True
            stack += [(i, at), (at, j)]
    return [p for p, k in zip(points, keep) if k]


def clean_name(name):
    name = name.replace(" Station", "").replace(" Bayside", "").strip()
    return name.replace("32nd/Commercial", "32nd & Commercial")


def main():
    zf = zipfile.ZipFile(sys.argv[1])
    stops = {s["stop_id"]: s for s in read(zf, "stops.txt")}
    trips = {t["trip_id"]: t for t in read(zf, "trips.txt") if t["route_id"] in LINES}
    seqs = defaultdict(list)
    for r in read(zf, "stop_times.txt"):
        if r["trip_id"] in trips:
            seqs[r["trip_id"]].append((int(r["stop_sequence"]), r["stop_id"]))

    patterns = defaultdict(Counter)
    for tid, t in trips.items():
        if t["direction_id"] == "0":
            patterns[t["route_id"]][(t["shape_id"], tuple(s for _, s in sorted(seqs[tid])))] += 1
    chosen = {}
    for rid, counter in patterns.items():
        chosen[rid] = max(counter, key=lambda k: (len(k[1]), counter[k]))

    shapes = defaultdict(list)
    wanted = {shape for shape, _ in chosen.values()}
    for r in read(zf, "shapes.txt"):
        if r["shape_id"] in wanted:
            shapes[r["shape_id"]].append(
                (int(r["shape_pt_sequence"]), float(r["shape_pt_lat"]), float(r["shape_pt_lon"]))
            )

    stations = {}
    lines = []
    for rid, (lid, lname, colour) in LINES.items():
        shape_id, stop_ids = chosen[rid]
        ids = []
        for sid in stop_ids:
            parent = stops[sid]["parent_station"] or sid
            parent = MERGE.get(parent, parent)
            p = stops[parent]
            stations.setdefault(parent, (clean_name(p["stop_name"]), float(p["stop_lat"]), float(p["stop_lon"])))
            ids.append(parent)
        pts = [(la, lo) for _, la, lo in sorted(shapes[shape_id])]
        pts = simplify(pts, SIMPLIFY_METRES)
        lines.append((lid, lname, colour, ids, pts))

    feed = next(read(zf, "feed_info.txt"))
    out = [
        "// Generated by scripts/build_network.py from the MTS GTFS feed",
        f"// ({feed['feed_version']}). Do not edit by hand.",
        "package org.nextcolor.trolleylog.data",
        "",
        "internal val NETWORK_STATIONS: List<Station> = listOf(",
    ]
    for sid, (name, lat, lon) in stations.items():
        out.append(f'    Station("{sid}", "{name}", {lat:.6f}, {lon:.6f}),')
    out += [")", "", "internal val NETWORK_LINES: List<Line> = listOf("]
    for lid, lname, colour, ids, pts in lines:
        out.append("    Line(")
        out.append(f'        "{lid}", "{lname}", 0x{colour:08X},')
        out.append("        listOf(" + ", ".join(f'"{i}"' for i in ids) + "),")
        out.append("        floatArrayOf(")
        flat = [f"{la:.5f}f, {lo:.5f}f" for la, lo in pts]
        for i in range(0, len(flat), 4):
            out.append("            " + ", ".join(flat[i:i + 4]) + ",")
        out.append("        ),")
        out.append("    ),")
    out.append(")")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n")
    print(f"{len(stations)} stations, " + ", ".join(f"{l[1]} {len(l[4])} points" for l in lines))


if __name__ == "__main__":
    main()
